using System.Text;
using AnsiCCore.Frontend.Ast;
using AnsiCCore.Semantics.Symbols;
using AnsiCCore.Semantics.Types;

namespace AnsiCCore.Emit;

/// <summary>
/// Translates an analyzed <see cref="TranslationUnit"/> into C# source. This is the first
/// vertical slice: scalar functions (integer/floating locals, parameters, and globals), the
/// full expression operator set, control flow, calls/recursion, and <c>return</c>. The emitted
/// program's entry point returns C <c>main</c>'s value as the process exit code, so behavior can
/// be verified by compiling and running the output.
/// </summary>
/// <remarks>
/// C uses <c>int</c> where C# uses <c>bool</c> (conditions and the logical/relational operators).
/// The emitter keeps value expressions typed as C integers and converts at the boundaries: see
/// the <c>EmitValue</c>/<c>EmitCondition</c> split in the expression partial.
/// </remarks>
public sealed partial class CSharpEmitter
{
    private readonly SemanticModel _model;
    private readonly StringBuilder _sb = new();
    private int _indent;
    private QualType? _currentReturnType;

    // Per-function local naming. C permits shadowing a name in an enclosing block; C# does not
    // (CS0136), so each local symbol gets a unique C# name and uses are keyed off the symbol.
    private readonly Dictionary<Symbol, string> _localNames = new();
    private readonly HashSet<string> _usedNames = new(StringComparer.Ordinal);

    private CSharpEmitter(SemanticModel model) => _model = model;

    /// <summary>Emits a complete C# compilation unit for <paramref name="unit"/>.</summary>
    public static string Emit(TranslationUnit unit, SemanticModel model)
    {
        var emitter = new CSharpEmitter(model);
        emitter.EmitTranslationUnit(unit);
        return emitter._sb.ToString();
    }

    private void EmitTranslationUnit(TranslationUnit unit)
    {
        Line("// <auto-generated> Transpiled from ANSI C by AnsiCCore. </auto-generated>");
        Line("using AnsiCCore.Runtime.Memory;");
        Line();
        Line("internal static class CProgram");
        OpenBrace();

        foreach (var item in unit.Items)
        {
            switch (item)
            {
                case FunctionDefinition f:
                    EmitFunction(f);
                    break;
                case Declaration d:
                    EmitGlobalDeclaration(d);
                    break;
            }
        }

        EmitEntryPoint(unit);
        EmitRuntimeHelpers();
        CloseBrace();
    }

    /// <summary>Small helpers the translation relies on (e.g. the C comma operator).</summary>
    private void EmitRuntimeHelpers()
    {
        Line();
        Line("// Evaluates both operands left-to-right and yields the right one (C comma operator).");
        Line("private static T Comma<T>(object? left, T right) => right;");
    }

    // --- functions --------------------------------------------------------

    private void EmitFunction(FunctionDefinition f)
    {
        if (!_model.SymbolsByNode.TryGetValue(f, out var symbol) || symbol.Type.Type is not FunctionType ft)
            throw new EmitException("function definition was not resolved by semantic analysis");

        if (!ft.HasPrototype && ft.Parameters.Count == 0 && HasParameters(f))
            throw new EmitException($"old-style (K&R) function '{symbol.Name}' is not supported yet");

        string returnType = TypeMapper.Map(ft.ReturnType);
        string name = Naming.Safe(symbol.Name);
        string parameters = string.Join(", ", ft.Parameters.Select(p =>
            $"{TypeMapper.Map(p.Type)} {Naming.Safe(p.Name ?? "_")}"));

        Line($"private static {returnType} {name}({parameters})");
        _currentReturnType = ft.ReturnType;
        _localNames.Clear();
        _usedNames.Clear();
        foreach (var p in ft.Parameters.Where(p => p.Name is not null))
            _usedNames.Add(Naming.Safe(p.Name!)); // reserve parameter names so inner locals don't collide
        EmitBlock(f.Body);
        _currentReturnType = null;
        Line();
    }

    private static bool HasParameters(FunctionDefinition f)
        => f.Declarator is FunctionDeclarator { Parameters.Kind: ParameterKind.IdentifierList } fd && fd.Parameters.Identifiers.Count > 0;

    // --- globals ----------------------------------------------------------

    private void EmitGlobalDeclaration(Declaration d)
    {
        if (d.Specifiers.IsTypedef) return;          // typedefs are compile-time only
        if (d.InitDeclarators.Count == 0) return;    // bare struct/enum/tag declaration

        foreach (var init in d.InitDeclarators)
        {
            if (!_model.SymbolsByNode.TryGetValue(init, out var symbol))
                continue;
            if (symbol.Kind == SymbolKind.Function)
                continue;                            // a function prototype — its definition emits the method
            if (symbol.Kind == SymbolKind.Typedef)
                continue;

            string type = TypeMapper.Map(symbol.Type);
            string name = Naming.Safe(symbol.Name);
            string value = init.Initializer is ExpressionInitializer ei
                ? EmitConvert(symbol.Type, ei.Expression)
                : "default";
            Line($"private static {type} {name} = {value};");
        }
    }

    // --- entry point ------------------------------------------------------

    private void EmitEntryPoint(TranslationUnit unit)
    {
        var main = unit.Items.OfType<FunctionDefinition>()
            .FirstOrDefault(f => _model.SymbolsByNode.TryGetValue(f, out var s) && s.Name == "main");
        if (main is null)
            return; // a translation unit need not define main (e.g. a library)

        var ft = (FunctionType)_model.SymbolsByNode[main].Type.Type;
        if (ft.Parameters.Count != 0)
            throw new EmitException("only 'int main(void)' is supported in this slice");

        Line("private static int Main()");
        OpenBrace();
        if (ft.ReturnType.Type is VoidType)
        {
            Line("main();");
            Line("return 0;");
        }
        else
        {
            Line("return unchecked((int)main());");
        }
        CloseBrace();
    }

    // --- local naming -----------------------------------------------------

    /// <summary>Allocates a unique C# name for a newly-declared local and records it for its uses.</summary>
    private string DeclareLocalName(Symbol symbol)
    {
        string baseName = Naming.Safe(symbol.Name);
        string name = baseName;
        for (int n = 2; !_usedNames.Add(name); n++)
            name = $"{baseName}_{n}";
        _localNames[symbol] = name;
        return name;
    }

    // --- output helpers ---------------------------------------------------

    private void Line() => _sb.Append('\n');

    private void Line(string text) => _sb.Append(' ', _indent * 4).Append(text).Append('\n');

    private void OpenBrace() { Line("{"); _indent++; }

    private void CloseBrace() { _indent--; Line("}"); }
}
