using System.Text;
using AnsiCCore.Frontend.Ast;
using AnsiCCore.Semantics.Symbols;
using AnsiCCore.Semantics.Types;

namespace AnsiCCore.Emit;

/// <summary>
/// Translates an analyzed <see cref="TranslationUnit"/> into C# source. The emitted program
/// targets the safe runtime memory model (<c>CMemory</c>/<c>CPtr</c>): objects whose address is
/// taken — and all arrays/structs/unions — live in memory, while other scalars and pointers stay
/// as plain C# values. A single static <c>CMemory</c> is the program's address space.
/// </summary>
/// <remarks>
/// Two impedance points drive the design. C uses <c>int</c> where C# uses <c>bool</c> — handled by
/// the <c>EmitValue</c>/<c>EmitCondition</c> split. And C objects have addresses — handled by the
/// <c>EmitValue</c>/<c>EmitAddress</c> split, where an lvalue in a memory-backed object lowers to a
/// <c>CMemory</c> read/write at its computed address.
/// </remarks>
public sealed partial class CSharpEmitter
{
    private readonly SemanticModel _model;
    private readonly MemoryPlan _plan;
    private readonly ExportRegistry _exports;
    private readonly StringBuilder _sb = new();
    private int _indent;

    private QualType? _currentReturnType;

    // Per-function state.
    private readonly Dictionary<Symbol, string> _localNames = new();      // symbol -> unique C# name
    private readonly Dictionary<Symbol, string> _addressOf = new();       // memory-backed local/param -> CPtr expr
    private readonly HashSet<string> _usedNames = new(StringComparer.Ordinal);
    private int _labelCounter;                                            // generates unique switch labels
    private readonly Stack<string?> _breakStack = new();                  // null = loop (C# break), else switch end label
    private Dictionary<Statement, string>? _switchCaseLabels;             // case/default node -> label (current switch)

    // Module-level state.
    private readonly Dictionary<Symbol, string> _globalAddress = new();   // memory-backed global -> CPtr field
    private readonly HashSet<string> _userFunctions = new(StringComparer.Ordinal);
    private readonly List<(string Field, byte[] Bytes)> _strings = [];
    private int _stringCounter;

    private CSharpEmitter(TranslationUnit unit, SemanticModel model, ExportRegistry exports)
    {
        _model = model;
        _plan = MemoryPlan.Build(unit, model);
        _exports = exports;
    }

    /// <summary>Emits C# for a translation unit, resolving external calls against <paramref name="exports"/>.</summary>
    public static string Emit(TranslationUnit unit, SemanticModel model, ExportRegistry? exports = null)
    {
        var emitter = new CSharpEmitter(unit, model, exports ?? ExportRegistry.Default);
        emitter.EmitTranslationUnit(unit);
        return emitter._sb.ToString();
    }

    private void EmitTranslationUnit(TranslationUnit unit)
    {
        foreach (var f in unit.Items.OfType<FunctionDefinition>())
            if (_model.SymbolsByNode.TryGetValue(f, out var s))
                _userFunctions.Add(s.Name);

        var globals = PlanGlobals(unit);

        Line("// <auto-generated> Transpiled from ANSI C by AnsiCCore. </auto-generated>");
        Line("#nullable enable");
        Line("using AnsiCCore.Runtime.Memory;");
        Line();
        Line("internal static class CProgram");
        OpenBrace();

        Line("private static readonly CMemory __mem = new CMemory();");
        Line();

        foreach (var g in globals)
            Line($"private static {(g.MemoryBacked ? "CPtr" : TypeMapper.Map(g.Type))} {g.Name};");
        if (globals.Count > 0) Line();

        foreach (var f in unit.Items.OfType<FunctionDefinition>())
            EmitFunction(f);

        EmitEntryPoint(unit);
        EmitStaticConstructor(globals);
        EmitRuntimeHelpers();
        EmitStringFields();

        CloseBrace();
    }

    // --- globals ----------------------------------------------------------

    private readonly record struct GlobalInfo(Symbol Symbol, string Name, bool MemoryBacked, QualType Type, Initializer? Initializer);

    private List<GlobalInfo> PlanGlobals(TranslationUnit unit)
    {
        // A global may appear more than once across translation units (a definition plus extern
        // declarations). Emit one field per name, keeping the initializer from the definition and
        // memory-backing it if any occurrence is address-taken.
        var globals = new List<GlobalInfo>();
        var byName = new Dictionary<string, int>(StringComparer.Ordinal);
        var symbolsByName = new Dictionary<string, List<Symbol>>(StringComparer.Ordinal);

        foreach (var d in unit.Items.OfType<Declaration>())
        {
            if (d.Specifiers.IsTypedef) continue;
            foreach (var init in d.InitDeclarators)
            {
                if (!_model.SymbolsByNode.TryGetValue(init, out var sym)) continue;
                if (sym.Kind is SymbolKind.Typedef or SymbolKind.Function) continue;

                bool memory = _plan.IsMemoryBacked(sym);
                string name = SymbolName(sym); // mangled for static globals; shared name for externals
                (symbolsByName.TryGetValue(name, out var list) ? list : symbolsByName[name] = []).Add(sym);

                if (byName.TryGetValue(name, out int idx))
                {
                    var cur = globals[idx];
                    globals[idx] = cur with { MemoryBacked = cur.MemoryBacked || memory, Initializer = cur.Initializer ?? init.Initializer };
                }
                else
                {
                    byName[name] = globals.Count;
                    globals.Add(new GlobalInfo(sym, name, memory, sym.Type, init.Initializer));
                }
            }
        }

        // Point every symbol that names a memory-backed global at its field.
        foreach (var g in globals.Where(g => g.MemoryBacked))
            foreach (var sym in symbolsByName[g.Name])
                _globalAddress[sym] = g.Name;

        return globals;
    }

    private void EmitStaticConstructor(List<GlobalInfo> globals)
    {
        if (_strings.Count == 0 && globals.Count == 0) return;

        Line("static CProgram()");
        OpenBrace();
        foreach (var (field, bytes) in _strings)
            Line($"{field} = __mem.AllocateStaticBytes(new byte[] {{ {string.Join(", ", bytes)} }});");

        foreach (var g in globals)
        {
            if (g.MemoryBacked)
            {
                long size = AllocationSize(g.Type.Type, g.Initializer);
                Line($"{g.Name} = __mem.Allocate({size}, RegionKind.Static);");
                if (g.Initializer is not null)
                    EmitInitializer(g.Type.Type, g.Name, g.Initializer);
            }
            else
            {
                string value = g.Initializer is ExpressionInitializer ei ? EmitConvert(g.Type, ei.Expression) : "default";
                Line($"{g.Name} = {value};");
            }
        }
        CloseBrace();
        Line();
    }

    // --- functions --------------------------------------------------------

    /// <summary>Name of the hidden base-pointer parameter injected into variadic functions.</summary>
    private const string VaListParam = "__va";

    private void EmitFunction(FunctionDefinition f)
    {
        if (!_model.SymbolsByNode.TryGetValue(f, out var symbol) || symbol.Type.Type is not FunctionType ft)
            throw new EmitException("function definition was not resolved by semantic analysis");
        if (!ft.HasPrototype && HasParameters(f))
            throw new EmitException($"old-style (K&R) function '{symbol.Name}' is not supported yet");

        string returnType = TypeMapper.Map(ft.ReturnType);
        string name = SymbolName(symbol);
        var paramList = ft.Parameters
            .Select(p => $"{TypeMapper.Map(p.Type)} {Naming.Safe(p.Name ?? "_")}")
            .ToList();
        // A variadic function takes a hidden base pointer to its promoted-argument region, which
        // the <stdarg.h> macros read through. (See CVarArgs / stdarg.h.)
        if (ft.IsVariadic) paramList.Add($"CPtr {VaListParam}");
        string parameters = string.Join(", ", paramList);

        Line($"private static {returnType} {name}({parameters})");

        _currentReturnType = ft.ReturnType;
        _localNames.Clear();
        _addressOf.Clear();
        _usedNames.Clear();
        _labelCounter = 0;
        _breakStack.Clear();
        _switchCaseLabels = null;
        foreach (var p in ft.Parameters.Where(p => p.Name is not null))
            _usedNames.Add(Naming.Safe(p.Name!));
        if (ft.IsVariadic) _usedNames.Add(VaListParam);

        OpenBrace();
        EmitParameterSpilling(f, ft);
        EmitBlockItems(f.Body.Items);
        CloseBrace();

        _currentReturnType = null;
        Line();
    }

    /// <summary>Spills address-taken scalar parameters into memory regions at function entry.</summary>
    private void EmitParameterSpilling(FunctionDefinition f, FunctionType ft)
    {
        var nodes = FindFunctionDeclarator(f.Declarator)?.Parameters.Parameters;
        if (nodes is null) return;

        for (int i = 0; i < ft.Parameters.Count && i < nodes.Count; i++)
        {
            var p = ft.Parameters[i];
            if (p.Name is null) continue;
            if (!_model.SymbolsByNode.TryGetValue(nodes[i], out var sym) || !_plan.IsMemoryBacked(sym)) continue;
            string paramName = Naming.Safe(p.Name);

            // A by-value struct/union parameter already arrives as a CPtr to the caller's copy;
            // use it directly as the object's address (no spill needed).
            if (p.Type.Type is RecordType)
            {
                _addressOf[sym] = paramName;
                continue;
            }
            if (p.Type.Type is ArrayType)
                throw new EmitException("array parameters by value are not supported");

            // Address-taken scalar/pointer parameter: spill its incoming value into a region.
            string addr = paramName + "__a";
            _addressOf[sym] = addr;
            Line($"CPtr {addr} = __mem.Allocate({MemoryAccess.SizeOf(p.Type.Type)}, RegionKind.Automatic);");
            Line($"__mem.Write{MemoryAccess.Suffix(p.Type.Type)}({addr}, {paramName});");
        }
    }

    private static FunctionDeclarator? FindFunctionDeclarator(Declarator d) => d switch
    {
        FunctionDeclarator fd => fd,
        PointerDeclarator p => FindFunctionDeclarator(p.Inner),
        ArrayDeclarator a => FindFunctionDeclarator(a.Inner),
        _ => null,
    };

    private static bool HasParameters(FunctionDefinition f)
        => f.Declarator is FunctionDeclarator { Parameters.Kind: ParameterKind.IdentifierList } fd && fd.Parameters.Identifiers.Count > 0;

    // --- entry point ------------------------------------------------------

    private void EmitEntryPoint(TranslationUnit unit)
    {
        var main = unit.Items.OfType<FunctionDefinition>()
            .FirstOrDefault(f => _model.SymbolsByNode.TryGetValue(f, out var s) && s.Name == "main");
        if (main is null) return;

        var ft = (FunctionType)_model.SymbolsByNode[main].Type.Type;
        bool returnsVoid = ft.ReturnType.Type is VoidType;

        if (ft.Parameters.Count == 0)
        {
            Line("private static int Main()");
            OpenBrace();
            EmitMainInvocation("main()", returnsVoid);
            CloseBrace();
            return;
        }

        // int main(int argc, char **argv): marshal the CLI arguments into the memory model, with a
        // synthetic argv[0] program name prepended (C# args omit it), so argc == args.Length + 1.
        if (!IsArgcArgv(ft))
            throw new EmitException("only 'int main(void)' and 'int main(int, char **)' are supported");

        Line("private static int Main(string[] args)");
        OpenBrace();
        Line("string[] __argv = new string[args.Length + 1];");
        Line("__argv[0] = \"program\";");
        Line("System.Array.Copy(args, 0, __argv, 1, args.Length);");
        Line("CPtr __argvPtr = AnsiCCore.Runtime.Library.CMarshal.BuildArgv(__mem, __argv);");
        EmitMainInvocation("main(__argv.Length, __argvPtr)", returnsVoid);
        CloseBrace();
    }

    /// <summary>
    /// Emits the body that calls C <c>main</c>: a normal return runs the <c>atexit</c> handlers
    /// (C89 §5.1.2.2.3), <c>exit</c> unwinds with its status, and <c>abort</c> maps to a conventional
    /// failure code (128 + SIGABRT).
    /// </summary>
    private void EmitMainInvocation(string call, bool returnsVoid)
    {
        Line("try");
        OpenBrace();
        if (returnsVoid)
        {
            Line($"{call};");
            Line("AnsiCCore.Runtime.Library.CProcess.RunAtExit(__mem);");
            Line("return 0;");
        }
        else
        {
            Line($"int __code = unchecked((int){call});");
            Line("AnsiCCore.Runtime.Library.CProcess.RunAtExit(__mem);");
            Line("return __code;");
        }
        CloseBrace();
        Line("catch (AnsiCCore.Runtime.Library.CExitException __e) { return __e.Code; }");
        Line("catch (AnsiCCore.Runtime.Library.CAbortException) { return 134; }");
    }

    /// <summary>True for the <c>main(int argc, char **argv)</c> signature (argv already adjusted to a pointer).</summary>
    private static bool IsArgcArgv(FunctionType ft)
        => ft.Parameters.Count == 2
            && ft.Parameters[0].Type.Type is IntegerType or EnumType
            && ft.Parameters[1].Type.Type is PointerType;

    private void EmitRuntimeHelpers()
    {
        Line();
        Line("private static T Comma<T>(object? left, T right) => right;");
        Line("private static T __Post<T>(T old, object? write) => old; // postfix ++/--: args evaluate left-to-right, so old is read before the store");
        Line("private static CPtr __PostAddPtr(ref CPtr p, long d) { CPtr old = p; p = p + d; return old; }");
        Line("private static CPtr __ByValue(CPtr src, long size) { CPtr d = __mem.Allocate(size, RegionKind.Automatic); __mem.Copy(d, src, size); return d; }");
    }

    private void EmitStringFields()
    {
        foreach (var (field, _) in _strings)
            Line($"private static CPtr {field};");
    }

    /// <summary>Interns a C string literal as static bytes; returns the field holding its CPtr.</summary>
    private string InternString(byte[] bytes)
    {
        string field = $"__str{_stringCounter++}";
        _strings.Add((field, bytes));
        return field;
    }

    // --- symbol naming ----------------------------------------------------

    private readonly Dictionary<Symbol, string> _staticNames = new();

    /// <summary>
    /// The C# name for a function/global symbol. External-linkage symbols keep their C name (so
    /// references across files resolve to one member); internal-linkage (static) symbols get a
    /// unique suffix so same-named statics in different files don't collide.
    /// </summary>
    private string SymbolName(Symbol symbol)
    {
        if (symbol.Storage != StorageClass.Static)
            return Naming.Safe(symbol.Name);
        if (!_staticNames.TryGetValue(symbol, out var name))
            _staticNames[symbol] = name = $"{Naming.Safe(symbol.Name)}__s{_staticNames.Count}";
        return name;
    }

    // --- local naming -----------------------------------------------------

    private string DeclareLocalName(Symbol symbol)
    {
        string baseName = Naming.Safe(symbol.Name);
        string name = baseName;
        for (int n = 2; !_usedNames.Add(name); n++)
            name = $"{baseName}_{n}";
        _localNames[symbol] = name;
        return name;
    }

    // --- output helpers ---------------------------------------------------

    private void Line() => _sb.Append('\n');
    private void Line(string text) => _sb.Append(' ', _indent * 4).Append(text).Append('\n');
    private void OpenBrace() { Line("{"); _indent++; }
    private void CloseBrace() { _indent--; Line("}"); }
}
